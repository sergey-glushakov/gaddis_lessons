# Эта программа демонстрирует выравнивание строковых литералов по центру.
name1 = "Марина"
name2 = "Сергей"
name3 = "Таня"
name4 = "Антон"
name5 = "Зоя"
name6 = "Яков"

# Вывод имен на экран.
print(f"***{name1:^20}***")
print(f"***{name2:^20}***")
print(f"***{name3:^20}***")
print(f"***{name4:^20}***")
print(f"***{name5:^20}***")
print(f"***{name6:^20}***")
